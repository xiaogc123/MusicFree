const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.join(__dirname, '..');
const sources = ['kugou', 'qq', 'bilibili', 'qishui'];

for (const name of sources) {
    const shared = fs.readFileSync(path.join(root, 'shared/api.js'), 'utf8');
    const source = fs.readFileSync(path.join(root, name, 'src/index.js'), 'utf8');
    const bundle = '// Generated by plugins/tools/build.cjs\n' +
        '(function (hostRequire) {\n' +
        'const shared = { exports: {} };\n' +
        '(function (module, require) {\n' + shared + '\n})(shared, hostRequire);\n' +
        '(function (module, require) {\n' + source + '\n})(module, function (name) {\n' +
        'if (name === "../../shared/api") return shared.exports;\n' +
        'throw new Error("Unsupported module: " + name);\n});\n})(require);\n';
    new vm.Script(bundle, { filename: name + '/plugin.js' });
    fs.mkdirSync(path.join(root, name, 'dist'), { recursive: true });
    fs.writeFileSync(path.join(root, name, 'dist/plugin.js'), bundle);
    console.log('Built ' + name + '/dist/plugin.js (' + Buffer.byteLength(bundle) + ' bytes)');
}

const plugins = ['netease', ...sources].map(function (name) {
    const module = { exports: {} };
    vm.runInNewContext(fs.readFileSync(path.join(root, name, 'dist/plugin.js'), 'utf8'), {
        module, require: function (name) {
            if (name !== 'axios') throw new Error('Unexpected runtime dependency: ' + name);
            return {};
        }, URL,
    });
    const plugin = module.exports;
    return { name: plugin.platform, version: plugin.version, url: plugin.srcUrl };
});
fs.writeFileSync(path.join(root, 'plugins.json'), JSON.stringify({
    desc: '网易云、酷狗、QQ 音乐、bilibili、汽水匿名整曲独立音源订阅。', plugins,
}, null, 2) + '\n');
console.log('Generated plugins.json with ' + plugins.length + ' plugins');
