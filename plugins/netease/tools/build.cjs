const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const root = path.join(__dirname, '..');
const modules = ['api', 'mapper', 'index'].map(function (name) {
    const filename = path.join(root, 'src', name + '.js');
    const source = fs.readFileSync(filename, 'utf8');
    new vm.Script(source, { filename });
    return JSON.stringify('./' + name) + ': function (module, exports, require) {\n' + source + '\n}';
});
const bundle = '// Generated by tools/build.cjs. Install this file in MusicFree.\n' +
    '(function (hostRequire) {\n' +
    'const modules = {\n' + modules.join(',\n') + '\n};\n' +
    'const cache = {};\n' +
    'function load(name) {\n' +
    '    if (name === "axios") return hostRequire(name);\n' +
    '    if (!modules[name]) throw new Error("Unknown module: " + name);\n' +
    '    if (!cache[name]) {\n' +
    '        const item = { exports: {} };\n' +
    '        cache[name] = item;\n' +
    '        modules[name](item, item.exports, load);\n' +
    '    }\n' +
    '    return cache[name].exports;\n' +
    '}\nmodule.exports = load("./index");\n})(require);\n';
new vm.Script(bundle, { filename: 'plugin.js' });
fs.mkdirSync(path.join(root, 'dist'), { recursive: true });
fs.writeFileSync(path.join(root, 'dist', 'plugin.js'), bundle);
console.log('Built dist/plugin.js (' + Buffer.byteLength(bundle) + ' bytes)');
